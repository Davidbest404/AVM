/// <summary>
/// Состояние любой системы АВМ. Используется для событий и визуала.
/// </summary>
public enum SystemState
{
    Normal,     // Работает штатно
    Warning,    // Предупреждение (лампа покраснела, волна на границе)
    Broken,     // Поломка (лампа погасла, волна ушла за допуск)
    Repairing   // Идёт ремонт игроком
}